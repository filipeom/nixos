# direnv helpers for Brazil workspaces. A package's .envrc only needs:
#
#   use brazil_rust
#
# Loaded by direnv (bash) before every .envrc; functions only, no side effects.

# Workspace root is the nearest ancestor holding Brazil's packageInfo.
_brazil_ws() {
  local info
  info=$(find_up packageInfo) || return 1
  dirname "$info"
}

use_brazil_rust() {
  local ws
  ws=$(_brazil_ws) || { log_error "use brazil_rust: not inside a Brazil workspace"; return 1; }

  export CARGO_HOME=$PWD/build/private/cargo-home # brazil's cargo home
  export CARGO_BUILD_JOBS=6 # don't crash please
  export RUST_MIN_STACK=67108864 # to run pe tests
  export RUST_ANALYZER=$HOME/.toolbox/bin/rust-analyzer # amazon's rust-analyzer

  # nextest's double-spawn re-execs /proc/self/exe, which breaks under the brazil
  # toolchain's loader wrapper ("__double-spawn: cannot open shared object file").
  export NEXTEST_DOUBLE_SPAWN=0
  export PATH=$PATH:$ws/env/Cargo-nextest-0.x/runtime/bin:$PWD/build/bin

  # cargo-brazil-toolchain only symlinks lib/libexec, not share, so zsh's
  # _cargo completion can't find <sysroot>/share/zsh/site-functions/_cargo.
  # Re-add the missing symlink each time direnv reloads (build/private is
  # regenerated by brazil-build/cargo brazil sync, which wipes it).
  local toolchain_share=$PWD/build/private/cargo-brazil-toolchain/share
  if [[ ! -e "$toolchain_share" ]]; then
    ln -s "$ws/env/Rust-1.x.standalone/runtime/share" "$toolchain_share" 2>/dev/null
  fi
}
